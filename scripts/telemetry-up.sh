#!/usr/bin/env bash
# Task 4: OpenSearch + OpenSearch Dashboards for the three telemetry streams.
# Safe to re-run: every step checks first; users, roles, index templates and the
# dashboard are re-applied each time, so the running stack matches the repository.
#
#   scripts/telemetry-up.sh           start/update the stack and set CI variables
#   scripts/telemetry-up.sh --down    stop it (data kept)
#   scripts/telemetry-up.sh --purge   stop it and delete its data and certificates
#
# Generated in .local/telemetry/ (git-ignored):
#   certs/        CA, node certificate (TLS for everyone), admin client certificate
#   *-password    one per user: admin, dashboards, shipper, ci, analyst
#   internal_users.yml   bcrypt hashes of those passwords
# Run it before scripts/staging-up.sh, which gives the VM's Fluent Bit the CA and
# the shipper password.
source "$(dirname "$0")/lib.sh"

TDIR="$REPO_ROOT/telemetry"
TSTATE="$STATE_DIR/telemetry"
CERTS="$TSTATE/certs"
OS_IMAGE="opensearchproject/opensearch:2.19.6"
USERS=(admin dashboards shipper ci analyst)

need docker curl openssl
[ -n "$PY" ] || die "python3 is required"

compose() {
  TELEMETRY_STATE="$TSTATE" OPENSEARCH_PORT="$OPENSEARCH_PORT" DASHBOARDS_PORT="$DASHBOARDS_PORT" \
  DASHBOARDS_PASSWORD="$(cat "$TSTATE/dashboards-password" 2>/dev/null || true)" \
    docker compose -p "$TELEMETRY_PROJECT" -f "$TDIR/compose.yml" "$@"
}

case "${1:-}" in
  --down)  compose down; ok "telemetry stack stopped (data kept)"; exit 0 ;;
  --purge) compose down -v; rm -rf "$TSTATE"; ok "telemetry stack, data and certificates removed"; exit 0 ;;
  "") ;;
  *) die "unknown option: $1" ;;
esac

# --------------------------------------------------------------------------- passwords
mkdir -p "$CERTS"
for u in "${USERS[@]}"; do token_file "telemetry/$u-password" >/dev/null; done
ok "passwords in $TSTATE (one per user)"

# --------------------------------------------------------------------------- certificates
# Own CA rather than the demo certificates: those use a private key published with
# every OpenSearch download, so anyone could impersonate the node.
if [ ! -s "$CERTS/ca.pem" ]; then
  log "Creating the telemetry CA and certificates"
  openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:3072 -out "$CERTS/ca.key" 2>/dev/null
  # Extensions as strict X.509 validation wants them (Python 3.13+ enforces it):
  # the CA's key usage marked critical, key identifiers on every certificate.
  openssl req -x509 -new -key "$CERTS/ca.key" -sha256 -days 3650 \
    -subj "/O=Northwind/OU=telemetry/CN=Northwind telemetry CA" \
    -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -addext "subjectKeyIdentifier=hash" -out "$CERTS/ca.pem"
  issue() {  # issue <name> <subject> <extensions>
    openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$CERTS/$1.key" 2>/dev/null
    openssl req -new -key "$CERTS/$1.key" -subj "$2" -out "$CERTS/$1.csr"
    printf '%s\n' "$3" >"$CERTS/$1.ext"
    openssl x509 -req -in "$CERTS/$1.csr" -CA "$CERTS/ca.pem" -CAkey "$CERTS/ca.key" -CAcreateserial \
      -days 825 -sha256 -extfile "$CERTS/$1.ext" -out "$CERTS/$1.pem" 2>/dev/null
    rm -f "$CERTS/$1.csr" "$CERTS/$1.ext"
  }
  issue node "/O=Northwind/OU=telemetry/CN=$TELEMETRY_HOST" \
"basicConstraints=CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth,clientAuth
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer
subjectAltName=DNS:$TELEMETRY_HOST,DNS:opensearch,DNS:localhost,IP:127.0.0.1"
  issue admin "/O=Northwind/OU=telemetry/CN=admin" \
"basicConstraints=CA:FALSE
keyUsage=critical,digitalSignature,keyEncipherment
extendedKeyUsage=clientAuth
subjectKeyIdentifier=hash
authorityKeyIdentifier=keyid,issuer"
  ok "CA and certificates created"
  CERTS_NEW=1
else
  ok "certificates exist"
fi
chmod 600 "$CERTS"/*.key 2>/dev/null || true

# --------------------------------------------------------------------------- users
# bcrypt hashes come from the security plugin's own tool, all in one container run
# (each JVM start takes seconds). Passwords go in through the environment.
users_file="$TSTATE/internal_users.yml"
stale=0; [ -s "$users_file" ] || stale=1
for u in "${USERS[@]}"; do [ "$TSTATE/$u-password" -nt "$users_file" ] && stale=1; done
if [ "$stale" = 1 ]; then
  log "Hashing user passwords"
  envs=(); script=""
  for u in "${USERS[@]}"; do
    envs+=(-e "PW_$u=$(cat "$TSTATE/$u-password")")
    script+="printf '%s ' $u; /usr/share/opensearch/plugins/opensearch-security/tools/hash.sh -env PW_$u | tail -1;"
  done
  hashes=$(docker run --rm "${envs[@]}" --entrypoint sh "$OS_IMAGE" -c "$script" | tr -d '\r')
  {
    printf '# Generated by scripts/telemetry-up.sh. Passwords: .local/telemetry/<user>-password\n'
    printf '_meta:\n  type: "internalusers"\n  config_version: 2\n'
    while read -r u h; do
      case "$u" in admin|dashboards) reserved=true ;; *) reserved=false ;; esac
      printf '%s:\n  hash: "%s"\n  reserved: %s\n  description: "%s"\n' "$u" "$h" "$reserved" "telemetry $u"
    done <<<"$hashes"
  } >"$users_file"
  [ "$(grep -c '^  hash: "\$2' "$users_file")" = "${#USERS[@]}" ] || die "password hashing failed"
  ok "internal_users.yml written"
else
  ok "internal_users.yml up to date"
fi

# --------------------------------------------------------------------------- stack
log "Starting OpenSearch and Dashboards"
compose up -d --wait --wait-timeout 300 opensearch
# The certificates are bind-mounted: a running node keeps the old ones until restarted.
if [ "${CERTS_NEW:-0}" = 1 ]; then
  compose restart   # Dashboards reads the CA at start, too
  compose up -d --wait --wait-timeout 300 opensearch
fi
ok "OpenSearch healthy"

# Re-apply users, roles and mappings: the security index keeps whatever it was first
# created with, so changes to the files only take effect through securityadmin.
docker exec telemetry-opensearch /usr/share/opensearch/plugins/opensearch-security/tools/securityadmin.sh \
  -cd /usr/share/opensearch/config/opensearch-security/ -icl -nhnv -h localhost \
  -cacert /usr/share/opensearch/config/certs/ca.pem \
  -cert /usr/share/opensearch/config/certs/admin.pem \
  -key /usr/share/opensearch/config/certs/admin.key >"$TSTATE/securityadmin.log" 2>&1 \
  || { tail -20 "$TSTATE/securityadmin.log" >&2; die "securityadmin failed"; }
ok "users and roles applied"

# Windows' curl (Schannel) cannot check revocation for a private CA that publishes
# no revocation list, and refuses the certificate; the chain is still verified.
CURL_TLS=(--cacert "$CERTS/ca.pem")
curl -V | grep -qi schannel && CURL_TLS+=(--ssl-no-revoke)
os() {  # os <METHOD> <path> [curl args]  -- OpenSearch REST API as admin
  local m="$1" p="$2"; shift 2
  curl -sS --fail-with-body "${CURL_TLS[@]}" -u "admin:$(cat "$TSTATE/admin-password")" \
    -H 'Content-Type: application/json' -X "$m" "https://127.0.0.1:$OPENSEARCH_PORT$p" "$@"
}
wait_until 120 "OpenSearch to accept the admin login" os GET /_cluster/health

for f in "$TDIR"/index-templates/*.json; do
  os PUT "/_index_template/$(basename "$f" .json)" --data-binary "@$f" >/dev/null
done
ok "index templates applied: $(cd "$TDIR/index-templates" && ls *.json | sed 's/\.json$//' | tr '\n' ' ')"

# Retention: application logs 30 days, pipeline data 180 days.
for pol in app-logs:30d:app-logs-* pipeline-data:180d:findings-*,scans-*,ci-jobs-*; do
  IFS=: read -r name age patterns <<<"$pol"
  body=$("$PY" -c 'import json,sys
n,a,p=sys.argv[1:4]
print(json.dumps({"policy":{"description":"delete after "+a,"default_state":"hot",
 "states":[{"name":"hot","actions":[],"transitions":[{"state_name":"delete","conditions":{"min_index_age":a}}]},
           {"name":"delete","actions":[{"delete":{}}],"transitions":[]}],
 "ism_template":[{"index_patterns":p.split(","),"priority":100}]}}))' "$name" "$age" "$patterns")
  if existing=$(os GET "/_plugins/_ism/policies/$name" 2>/dev/null); then
    seq_no=$(printf '%s' "$existing" | json_get 'd["_seq_no"]')
    term=$(printf '%s' "$existing" | json_get 'd["_primary_term"]')
    os PUT "/_plugins/_ism/policies/$name?if_seq_no=$seq_no&if_primary_term=$term" -d "$body" >/dev/null
  else
    os PUT "/_plugins/_ism/policies/$name" -d "$body" >/dev/null
  fi
done
ok "retention policies applied"

compose up -d --wait --wait-timeout 300 dashboards
osd() {  # osd <METHOD> <path> [curl args]  -- Dashboards API as admin
  local m="$1" p="$2"; shift 2
  curl -sS --fail-with-body -u "admin:$(cat "$TSTATE/admin-password")" -H 'osd-xsrf: true' \
    -X "$m" "http://127.0.0.1:$DASHBOARDS_PORT$p" "$@"
}
wait_until 300 "Dashboards" osd GET /api/status
ndjson="$TSTATE/dashboard.ndjson"
PYTHONPATH="$REPO_ROOT/tools" "$PY" -m nwtelemetry.dashboard >"$ndjson"
result=$(osd POST "/api/saved_objects/_import?overwrite=true" -F "file=@$ndjson")
printf '%s' "$result" | json_get 'd["success"]' | grep -q True \
  || die "dashboard import failed: $result"
ok "dashboard imported ($(printf '%s' "$result" | json_get 'd["successCount"]') saved objects)"

# --------------------------------------------------------------------------- CI variables
if [ -s "$STATE_DIR/root-token" ]; then
  PROJECT_ID=$(project_id)
  nl=$'\n'
  set_project_var "$PROJECT_ID" TELEMETRY_URL      "https://$TELEMETRY_HOST:$OPENSEARCH_PORT" env_var false
  set_project_var "$PROJECT_ID" TELEMETRY_CA       "$(cat "$CERTS/ca.pem")$nl"                  file    false
  set_project_var "$PROJECT_ID" TELEMETRY_USER     ci                                         env_var false
  set_project_var "$PROJECT_ID" TELEMETRY_PASSWORD "$(cat "$TSTATE/ci-password")"             env_var true true

  # The report job reads this pipeline's jobs from the GitLab API. A project access
  # token limited to read_api; the job token cannot list a pipeline's jobs.
  tok=$(api GET "/projects/$PROJECT_ID/variables/TELEMETRY_GITLAB_TOKEN" 2>/dev/null | json_get 'd["value"]' 2>/dev/null || true)
  if [ -z "$tok" ] || ! curl -sf -H "PRIVATE-TOKEN: $tok" "$GITLAB_URL/api/v4/personal_access_tokens/self" >/dev/null; then
    expires=$("$PY" -c 'import datetime;print((datetime.date.today()+datetime.timedelta(days=364)).isoformat())' | tr -d '\r')
    tok=$(api POST "/projects/$PROJECT_ID/access_tokens" \
      --data-urlencode name=telemetry-report --data-urlencode 'scopes[]=read_api' \
      --data-urlencode access_level=20 --data-urlencode "expires_at=$expires" | json_get 'd["token"]')
    set_project_var "$PROJECT_ID" TELEMETRY_GITLAB_TOKEN "$tok" env_var true true
    ok "project access token for the report job created (read_api, expires $expires)"
  fi
  ok "CI variables set (TELEMETRY_PASSWORD and TELEMETRY_GITLAB_TOKEN are protected and masked)"
else
  warn "no GitLab token yet: run scripts/gitlab-up.sh, then this script again, to set the CI variables"
fi

cat <<EOF

Telemetry stack ready.
  OpenSearch   https://127.0.0.1:$OPENSEARCH_PORT   (CA: $CERTS/ca.pem)
  Dashboards   http://127.0.0.1:$DASHBOARDS_PORT    user analyst (read-only), password in $TSTATE/analyst-password
                                                     user admin, password in $TSTATE/admin-password
  Trend report scripts/trend --since 7d
EOF
